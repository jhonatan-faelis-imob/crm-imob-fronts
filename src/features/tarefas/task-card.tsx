import { Check, Link2, Pencil, Trash2, User, X } from 'lucide-react'
import Link from 'next/link'
import { useState } from 'react'
import { Avatar, AvatarFallback } from '@/components/ui/avatar'
import { ConfirmDialog } from '@/components/ui/confirm-dialog'
import { getInitials } from '@/lib/utils'
import type { Task } from '@/types'
import { AutoTaskChip } from './components/auto-task-chip'
import { PRIORITY_META, TASK_TYPE_META } from './constants'
import { formatTime, isOverdue, isToday } from './date-utils'

export function TaskCard({
  task,
  parentTask,
  isNew,
  onComplete,
  onEdit,
  onDelete,
  onOpenDetail,
}: {
  task: Task
  parentTask?: Task
  isNew?: boolean
  onComplete: (task: Task) => void
  onEdit: (task: Task) => void
  onDelete: (taskId: string) => void
  onOpenDetail: (task: Task) => void
}) {
  const [showDeleteConfirm, setShowDeleteConfirm] = useState(false)

  const typeMeta = TASK_TYPE_META[task.type]
  const TypeIcon = typeMeta.icon
  const priorityMeta = PRIORITY_META[task.priority]
  const overdue = task.status === 'pendente' && isOverdue(task.dueDate)
  const dueToday = task.status === 'pendente' && isToday(task.dueDate)
  const isDone = task.status === 'concluida'
  const isCancelled = task.status === 'cancelada'

  return (
    <>
    <div
      role="button"
      tabIndex={0}
      onClick={() => onOpenDetail(task)}
      onKeyDown={(event) => {
        if (event.key === 'Enter' || event.key === ' ') onOpenDetail(task)
      }}
      className={`group relative flex cursor-pointer items-start gap-3 rounded-[16px] border-[0.5px] border-l-[3px] border-line border-l-transparent bg-paper p-4 transition-colors hover:border-l-brand hover:bg-[#FAFAFA] ${
        isCancelled ? 'opacity-60' : ''
      }`}
    >
      <button
        type="button"
        role="checkbox"
        aria-checked={isDone}
        aria-label={isDone ? 'Tarefa concluída' : 'Marcar como concluída'}
        onClick={(event) => {
          event.stopPropagation()
          if (task.status === 'pendente') onComplete(task)
        }}
        disabled={task.status !== 'pendente'}
        className={`mt-0.5 flex h-5 w-5 shrink-0 items-center justify-center rounded-full border-[1.5px] transition-colors ${
          isDone
            ? 'border-success bg-success text-paper'
            : isCancelled
              ? 'cursor-not-allowed border-line bg-canvas text-line-strong'
              : 'cursor-pointer border-line hover:border-brand'
        }`}
      >
        {isDone && <Check className="h-3 w-3" />}
        {isCancelled && <X className="h-3 w-3" />}
      </button>

      <span
        className="flex h-9 w-9 shrink-0 items-center justify-center rounded-full"
        style={{ backgroundColor: typeMeta.bg, color: typeMeta.text }}
      >
        <TypeIcon className="h-4 w-4" />
      </span>

      <div className="min-w-0 flex-1">
        <div className="flex flex-wrap items-center gap-2">
          <p
            className={`text-sm font-medium ${
              isDone ? 'text-muted-foreground line-through' : 'text-brand'
            }`}
          >
            {task.title}
          </p>
          {isNew && (
            <span className="animate-pulse rounded-full bg-brand px-2 py-0.5 text-[11px] font-medium text-paper">
              Nova
            </span>
          )}
          {overdue && (
            <span className="rounded-full bg-[#FFEBEE] px-2 py-0.5 text-[11px] font-medium text-danger">
              Vencida
            </span>
          )}
          {dueToday && (
            <span className="rounded-full bg-[#FFF3E0] px-2 py-0.5 text-[11px] font-medium text-warning">
              Hoje
            </span>
          )}
          {task.autoGenerated && <AutoTaskChip />}
          {task.hasNextTask && (
            <span title="Ao concluir, gera a próxima tarefa automaticamente" className="text-muted-foreground">
              <Link2 className="h-3.5 w-3.5" />
            </span>
          )}
        </div>

        {task.leadName && task.leadId && (
          <Link
            href={`/leads/${task.leadId}`}
            onClick={(event) => event.stopPropagation()}
            className="mt-1 flex items-center gap-1 text-xs text-muted-foreground hover:text-brand"
          >
            <User className="h-3 w-3" />
            {task.leadName}
          </Link>
        )}

        {parentTask && (
          <p className="mt-1 text-[11px] text-muted-foreground">↳ Originada de: {parentTask.title}</p>
        )}
      </div>

      <div className="flex shrink-0 flex-col items-end gap-1.5">
        <div className="flex items-center gap-1.5">
          <div className="hidden items-center gap-1 group-hover:flex">
            <button
              type="button"
              aria-label="Editar tarefa"
              onClick={(event) => {
                event.stopPropagation()
                onEdit(task)
              }}
              className="rounded-[6px] p-1 text-muted-foreground hover:bg-canvas hover:text-brand"
            >
              <Pencil className="h-3.5 w-3.5" />
            </button>
            <button
              type="button"
              aria-label="Excluir tarefa"
              title="Excluir tarefa"
              onClick={(event) => {
                event.stopPropagation()
                setShowDeleteConfirm(true)
              }}
              className="rounded-[6px] p-1 text-muted-foreground hover:bg-[#FFEBEE] hover:text-danger"
            >
              <Trash2 className="h-3.5 w-3.5" />
            </button>
          </div>
          <span
            className="rounded-full px-2 py-0.5 text-[11px] font-medium"
            style={{ backgroundColor: priorityMeta.bg, color: priorityMeta.text }}
          >
            {priorityMeta.label}
          </span>
        </div>
        <span className="text-xs text-muted-foreground">{formatTime(task.dueDate)}</span>
        <Avatar size="sm">
          <AvatarFallback className="bg-line text-brand">
            {getInitials(task.assignedToName)}
          </AvatarFallback>
        </Avatar>
      </div>
    </div>

    <ConfirmDialog
      open={showDeleteConfirm}
      onOpenChange={setShowDeleteConfirm}
      title="Excluir tarefa?"
      description={
        <>
          A tarefa <strong>&quot;{task.title}&quot;</strong> será excluída e removida da sua lista de
          pendentes. Essa ação não pode ser desfeita.
        </>
      }
      confirmLabel="Sim, excluir"
      onConfirm={() => {
        setShowDeleteConfirm(false)
        onDelete(task.id)
      }}
    />
    </>
  )
}
